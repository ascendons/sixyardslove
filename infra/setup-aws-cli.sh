#!/usr/bin/env bash
# ============================================================
# Six Yards Love E-com — Full AWS Setup via CLI (no domain required)
# ============================================================
# Usage:
#   chmod +x infra/setup-aws-cli.sh
#   ./infra/setup-aws-cli.sh
#
# Prerequisites:
#   brew install awscli
#   aws configure   ← run this first (enter key/secret/region/json)
#
# What this script creates:
#   1. S3 bucket  (private, CloudFront-only access)
#   2. CloudFront distribution (HTTPS via *.cloudfront.net)
#   3. EC2 t3.micro (Ubuntu 24.04) + security group + Elastic IP
#   4. IAM deploy user (minimal permissions for GitHub Actions)
#   5. Prints all values you need for GitHub Secrets
# ============================================================

set -euo pipefail

# ── Config ───────────────────────────────────────────────────────────────────
REGION="${AWS_REGION:-ap-south-1}"          # change to us-east-1 for global
BUCKET_NAME="syl-frontend-$(date +%s)"   # unique suffix avoids name conflicts
EC2_KEY_NAME="syl-ec2-key"
SG_NAME="syl-backend-sg"
IAM_USER="syl-github-deploy"
APP_NAME="ecom-backend"

# ── Colors ───────────────────────────────────────────────────────────────────
GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
info()    { echo -e "${GREEN}[INFO]${NC}  $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
section() { echo -e "\n${YELLOW}══════════════════════════════════════════${NC}"; \
            echo -e "${YELLOW}  $*${NC}"; \
            echo -e "${YELLOW}══════════════════════════════════════════${NC}"; }

# ── Preflight check ──────────────────────────────────────────────────────────
section "0. Preflight Checks"
command -v aws  >/dev/null 2>&1 || { echo "${RED}ERROR: aws cli not found. Run: brew install awscli${NC}"; exit 1; }
command -v jq   >/dev/null 2>&1 || { echo "${RED}ERROR: jq not found. Run: brew install jq${NC}"; exit 1; }
aws sts get-caller-identity --region "$REGION" > /dev/null 2>&1 || \
  { echo "${RED}ERROR: AWS credentials not configured. Run: aws configure${NC}"; exit 1; }
info "AWS credentials OK"
ACCOUNT_ID=$(aws sts get-caller-identity --query Account --output text)
info "Account ID: $ACCOUNT_ID | Region: $REGION"

# ── Output file ──────────────────────────────────────────────────────────────
OUTPUT_FILE="infra/aws-outputs.env"
echo "# Generated by setup-aws-cli.sh — $(date)" > "$OUTPUT_FILE"
echo "# Add these as GitHub Secrets in your repo" >> "$OUTPUT_FILE"

# ─────────────────────────────────────────────────────────────────────────────
section "1. S3 Bucket (Private — CloudFront Only)"
# ─────────────────────────────────────────────────────────────────────────────

# us-east-1 doesn't accept --create-bucket-configuration
if [ "$REGION" = "us-east-1" ]; then
  aws s3api create-bucket \
    --bucket "$BUCKET_NAME" \
    --region "$REGION" 2>/dev/null || warn "Bucket $BUCKET_NAME may already exist"
else
  aws s3api create-bucket \
    --bucket "$BUCKET_NAME" \
    --region "$REGION" \
    --create-bucket-configuration LocationConstraint="$REGION" 2>/dev/null || \
    warn "Bucket $BUCKET_NAME may already exist"
fi

# Block all public access
aws s3api put-public-access-block \
  --bucket "$BUCKET_NAME" \
  --public-access-block-configuration \
    "BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true"

info "S3 bucket created: $BUCKET_NAME"
echo "S3_BUCKET_NAME=$BUCKET_NAME" >> "$OUTPUT_FILE"

# ─────────────────────────────────────────────────────────────────────────────
section "2. CloudFront Distribution (HTTPS via *.cloudfront.net)"
# ─────────────────────────────────────────────────────────────────────────────

# Create OAC (Origin Access Control)
OAC_ID=$(aws cloudfront create-origin-access-control \
  --origin-access-control-config \
    "Name=syl-oac,Description=Six Yards Love OAC,SigningProtocol=sigv4,SigningBehavior=always,OriginAccessControlOriginType=s3" \
  --query 'OriginAccessControl.Id' --output text 2>/dev/null || echo "")

if [ -z "$OAC_ID" ]; then
  # If OAC already exists, fetch it
  OAC_ID=$(aws cloudfront list-origin-access-controls \
    --query "OriginAccessControlList.Items[?Name=='syl-oac'].Id" \
    --output text)
fi
info "OAC ID: $OAC_ID"

# Create distribution (no custom domain — uses *.cloudfront.net)
CF_CONFIG=$(cat <<EOF
{
  "CallerReference": "syl-$(date +%s)",
  "Origins": {
    "Quantity": 1,
    "Items": [{
      "Id": "S3-$BUCKET_NAME",
      "DomainName": "$BUCKET_NAME.s3.$REGION.amazonaws.com",
      "OriginAccessControlId": "$OAC_ID",
      "S3OriginConfig": { "OriginAccessIdentity": "" }
    }]
  },
  "DefaultCacheBehavior": {
    "TargetOriginId": "S3-$BUCKET_NAME",
    "ViewerProtocolPolicy": "redirect-to-https",
    "CachePolicyId": "658327ea-f89d-4fab-a63d-7e88639e58f6",
    "Compress": true,
    "AllowedMethods": {
      "Quantity": 2,
      "Items": ["GET","HEAD"],
      "CachedMethods": { "Quantity": 2, "Items": ["GET","HEAD"] }
    }
  },
  "CustomErrorResponses": {
    "Quantity": 2,
    "Items": [
      {"ErrorCode": 403, "ResponsePagePath": "/index.html", "ResponseCode": "200", "ErrorCachingMinTTL": 0},
      {"ErrorCode": 404, "ResponsePagePath": "/index.html", "ResponseCode": "200", "ErrorCachingMinTTL": 0}
    ]
  },
  "Comment": "Six Yards Love Frontend",
  "DefaultRootObject": "index.html",
  "Enabled": true,
  "HttpVersion": "http2",
  "PriceClass": "PriceClass_100"
}
EOF
)

CF_RESULT=$(aws cloudfront create-distribution \
  --distribution-config "$CF_CONFIG" \
  --query 'Distribution.[Id,DomainName]' \
  --output text)

CF_DIST_ID=$(echo "$CF_RESULT" | awk '{print $1}')
CF_DOMAIN=$(echo "$CF_RESULT" | awk '{print $2}')

info "CloudFront Distribution ID: $CF_DIST_ID"
info "CloudFront Domain: https://$CF_DOMAIN"
echo "CLOUDFRONT_DISTRIBUTION_ID=$CF_DIST_ID" >> "$OUTPUT_FILE"
echo "CLOUDFRONT_DOMAIN=https://$CF_DOMAIN" >> "$OUTPUT_FILE"

# Attach S3 bucket policy so CloudFront can read objects
BUCKET_POLICY=$(cat <<EOF
{
  "Version": "2012-10-17",
  "Statement": [{
    "Sid": "AllowCloudFrontOAC",
    "Effect": "Allow",
    "Principal": { "Service": "cloudfront.amazonaws.com" },
    "Action": "s3:GetObject",
    "Resource": "arn:aws:s3:::$BUCKET_NAME/*",
    "Condition": {
      "StringEquals": {
        "AWS:SourceArn": "arn:aws:cloudfront::$ACCOUNT_ID:distribution/$CF_DIST_ID"
      }
    }
  }]
}
EOF
)
aws s3api put-bucket-policy --bucket "$BUCKET_NAME" --policy "$BUCKET_POLICY"
info "S3 bucket policy updated for CloudFront OAC"

# ─────────────────────────────────────────────────────────────────────────────
section "3. EC2 Key Pair"
# ─────────────────────────────────────────────────────────────────────────────
KEY_FILE="$HOME/.ssh/${EC2_KEY_NAME}.pem"

if [ -f "$KEY_FILE" ]; then
  warn "Key file $KEY_FILE already exists — skipping key creation"
else
  aws ec2 create-key-pair \
    --key-name "$EC2_KEY_NAME" \
    --region "$REGION" \
    --query 'KeyMaterial' \
    --output text > "$KEY_FILE"
  chmod 400 "$KEY_FILE"
  info "Key pair saved to $KEY_FILE"
fi
echo "EC2_KEY_FILE=$KEY_FILE" >> "$OUTPUT_FILE"
echo "EC2_USERNAME=ubuntu" >> "$OUTPUT_FILE"

# ─────────────────────────────────────────────────────────────────────────────
section "4. Security Group"
# ─────────────────────────────────────────────────────────────────────────────
MY_IP=$(curl -s https://checkip.amazonaws.com)
info "Your public IP: $MY_IP"

# Get default VPC
VPC_ID=$(aws ec2 describe-vpcs \
  --filters "Name=is-default,Values=true" \
  --region "$REGION" \
  --query 'Vpcs[0].VpcId' --output text)
info "Default VPC: $VPC_ID"

# Create security group
SG_ID=$(aws ec2 create-security-group \
  --group-name "$SG_NAME" \
  --description "Six Yards Love backend security group" \
  --vpc-id "$VPC_ID" \
  --region "$REGION" \
  --query 'GroupId' --output text 2>/dev/null || \
  aws ec2 describe-security-groups \
    --filters "Name=group-name,Values=$SG_NAME" \
    --region "$REGION" \
    --query 'SecurityGroups[0].GroupId' --output text)

info "Security Group: $SG_ID"

# Add rules (ignore errors if rules already exist)
# SSH — your IP only
aws ec2 authorize-security-group-ingress \
  --group-id "$SG_ID" --region "$REGION" \
  --protocol tcp --port 22 --cidr "${MY_IP}/32" 2>/dev/null || true

# HTTP — world (Nginx, port 80)
aws ec2 authorize-security-group-ingress \
  --group-id "$SG_ID" --region "$REGION" \
  --protocol tcp --port 80 --cidr "0.0.0.0/0" 2>/dev/null || true

# HTTPS — world (port 443, for future SSL)
aws ec2 authorize-security-group-ingress \
  --group-id "$SG_ID" --region "$REGION" \
  --protocol tcp --port 443 --cidr "0.0.0.0/0" 2>/dev/null || true

info "Security group rules added (SSH:$MY_IP, HTTP:all, HTTPS:all)"

# ─────────────────────────────────────────────────────────────────────────────
section "5. EC2 Instance (Ubuntu 24.04, t3.micro)"
# ─────────────────────────────────────────────────────────────────────────────

# Get latest Ubuntu 24.04 LTS AMI
AMI_ID=$(aws ec2 describe-images \
  --region "$REGION" \
  --owners 099720109477 \
  --filters \
    "Name=name,Values=ubuntu/images/hvm-ssd-gp3/ubuntu-noble-24.04-amd64-server-*" \
    "Name=state,Values=available" \
  --query 'sort_by(Images, &CreationDate)[-1].ImageId' \
  --output text)
info "Latest Ubuntu 24.04 AMI: $AMI_ID"

# User-data script — installs Java, Nginx, PostgreSQL, sets up app dir
USER_DATA=$(base64 < infra/ec2-bootstrap.sh)

# Launch instance
INSTANCE_ID=$(aws ec2 run-instances \
  --image-id "$AMI_ID" \
  --instance-type t3.micro \
  --key-name "$EC2_KEY_NAME" \
  --security-group-ids "$SG_ID" \
  --region "$REGION" \
  --user-data "$USER_DATA" \
  --block-device-mappings '[{"DeviceName":"/dev/sda1","Ebs":{"VolumeSize":20,"VolumeType":"gp3","DeleteOnTermination":true}}]' \
  --tag-specifications "ResourceType=instance,Tags=[{Key=Name,Value=syl-backend}]" \
  --query 'Instances[0].InstanceId' \
  --output text)

info "Instance launched: $INSTANCE_ID"
info "Waiting for instance to enter running state..."
aws ec2 wait instance-running --instance-ids "$INSTANCE_ID" --region "$REGION"
info "Instance is running"

# ─────────────────────────────────────────────────────────────────────────────
section "6. Elastic IP"
# ─────────────────────────────────────────────────────────────────────────────
EIP_ALLOC=$(aws ec2 allocate-address \
  --domain vpc \
  --region "$REGION" \
  --query '[AllocationId,PublicIp]' \
  --output text)

EIP_ALLOC_ID=$(echo "$EIP_ALLOC" | awk '{print $1}')
EC2_PUBLIC_IP=$(echo "$EIP_ALLOC" | awk '{print $2}')

aws ec2 associate-address \
  --instance-id "$INSTANCE_ID" \
  --allocation-id "$EIP_ALLOC_ID" \
  --region "$REGION" > /dev/null

info "Elastic IP: $EC2_PUBLIC_IP (attached to $INSTANCE_ID)"
echo "EC2_HOST=$EC2_PUBLIC_IP" >> "$OUTPUT_FILE"

# ─────────────────────────────────────────────────────────────────────────────
section "7. IAM Deploy User (for GitHub Actions)"
# ─────────────────────────────────────────────────────────────────────────────

# Create user
aws iam create-user --user-name "$IAM_USER" 2>/dev/null || warn "IAM user $IAM_USER already exists"

# S3 policy
S3_POLICY_ARN=$(aws iam create-policy \
  --policy-name "syl-s3-deploy" \
  --policy-document "{
    \"Version\": \"2012-10-17\",
    \"Statement\": [{
      \"Effect\": \"Allow\",
      \"Action\": [\"s3:PutObject\",\"s3:DeleteObject\",\"s3:ListBucket\",\"s3:GetObject\"],
      \"Resource\": [
        \"arn:aws:s3:::$BUCKET_NAME\",
        \"arn:aws:s3:::$BUCKET_NAME/*\"
      ]
    }]
  }" \
  --query 'Policy.Arn' --output text 2>/dev/null || \
  aws iam list-policies \
    --query "Policies[?PolicyName=='syl-s3-deploy'].Arn" \
    --output text)

# CloudFront invalidation policy
CF_POLICY_ARN=$(aws iam create-policy \
  --policy-name "syl-cf-invalidate" \
  --policy-document "{
    \"Version\": \"2012-10-17\",
    \"Statement\": [{
      \"Effect\": \"Allow\",
      \"Action\": \"cloudfront:CreateInvalidation\",
      \"Resource\": \"arn:aws:cloudfront::$ACCOUNT_ID:distribution/$CF_DIST_ID\"
    }]
  }" \
  --query 'Policy.Arn' --output text 2>/dev/null || \
  aws iam list-policies \
    --query "Policies[?PolicyName=='syl-cf-invalidate'].Arn" \
    --output text)

# Attach policies
aws iam attach-user-policy --user-name "$IAM_USER" --policy-arn "$S3_POLICY_ARN" 2>/dev/null || true
aws iam attach-user-policy --user-name "$IAM_USER" --policy-arn "$CF_POLICY_ARN" 2>/dev/null || true

# Create access key
IAM_KEYS=$(aws iam create-access-key \
  --user-name "$IAM_USER" \
  --query 'AccessKey.[AccessKeyId,SecretAccessKey]' \
  --output text)

IAM_KEY_ID=$(echo "$IAM_KEYS" | awk '{print $1}')
IAM_KEY_SECRET=$(echo "$IAM_KEYS" | awk '{print $2}')

echo "AWS_ACCESS_KEY_ID=$IAM_KEY_ID" >> "$OUTPUT_FILE"
echo "AWS_SECRET_ACCESS_KEY=$IAM_KEY_SECRET" >> "$OUTPUT_FILE"
echo "AWS_REGION=$REGION" >> "$OUTPUT_FILE"
info "IAM user created with access keys"

# ─────────────────────────────────────────────────────────────────────────────
section "DONE — GitHub Secrets Summary"
# ─────────────────────────────────────────────────────────────────────────────
echo ""
echo -e "${GREEN}All secrets have been saved to: $OUTPUT_FILE${NC}"
echo -e "${RED}⚠  KEEP THIS FILE PRIVATE — contains real AWS credentials${NC}"
echo ""
echo "──────────────────────────────────────────────────────────────"
echo "  Copy these into GitHub → Settings → Secrets → Actions"
echo "──────────────────────────────────────────────────────────────"
cat "$OUTPUT_FILE" | grep -v "^#"
echo ""
echo "  VITE_API_URL=http://$EC2_PUBLIC_IP/api"
echo "  EC2_SSH_KEY=<contents of $KEY_FILE>"
echo ""
echo -e "${YELLOW}Next step: Run EC2 bootstrap manually (takes ~3min):${NC}"
echo "  ssh -i $KEY_FILE ubuntu@$EC2_PUBLIC_IP"
echo "  # Bootstrap runs automatically via user-data."
echo "  # Check progress: sudo tail -f /var/log/cloud-init-output.log"
echo ""
echo -e "${YELLOW}Frontend URL:${NC} https://$CF_DOMAIN"
echo -e "${YELLOW}Backend URL:${NC}  http://$EC2_PUBLIC_IP/api/..."
echo "──────────────────────────────────────────────────────────────"
